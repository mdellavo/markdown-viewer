/// Options that affect the surrounding HTML page, not the Markdown itself.
#[derive(Debug, Clone, Default)]
pub struct PageOptions {
    pub title: String,
    /// Initial theme; the viewer UI can switch it.
    pub theme: Theme,
    pub style: Style,
    /// Extra CSS appended after the built-in styles (`--css`).
    pub custom_css: Option<String>,
    /// Include the viewer UI: toolbar, contents/files sidebar, keyboard
    /// shortcuts, copy buttons (everything except `-o` exports and PDFs).
    pub ui: bool,
    /// For served pages: the document's path relative to the served root,
    /// used to subscribe to its live updates.
    pub doc: Option<String>,
    /// Sidebar to show initially: "contents", "files", or none.
    pub sidebar: Option<String>,
    /// Source line to scroll back to (the remembered reading position).
    pub resume_line: Option<u32>,
    /// Remembered text size (multiple of normal).
    pub font_scale: Option<f32>,
    /// Show what changed since the last git commit.
    pub git_changes: bool,
    /// Leave the word count and reading time out of the toolbar.
    pub hide_word_count: bool,
    /// Recent files are remembered: served pages get a Recent tab.
    pub recent: bool,
    /// The theme was given with `--theme`; a standalone page shouldn't
    /// replace it with one remembered in the browser.
    pub fixed_theme: bool,
    /// Number headings (1, 1.1, 1.2, …).
    pub number_headings: bool,
    /// The page is served by our HTTP server, so it can load extra
    /// resources (mermaid.js) from it instead of inlining them.
    pub served: bool,
    /// Include the live-reload script (requires `served`).
    pub live: bool,
    /// When the server stops, close the window instead of just showing a
    /// "stopped" banner (requires `live`).
    pub close_on_exit: bool,
    /// Optional `<base href>` so relative links resolve somewhere else
    /// (used when the page is written to a temp dir).
    pub base_href: Option<String>,
    /// A page of a static site (`-o DIR` for a folder): the path from this
    /// page up to the site's root (`""` or `"../…"`). Libraries load from
    /// `_mdv/` there, and the Files sidebar lists the site's pages from
    /// `_mdv/files.js`.
    pub site_root: Option<String>,
    /// The viewer can change settings (the settings dialog).
    pub settings: bool,
    /// The viewer can show the page's Markdown source.
    pub source: bool,
    /// Show when the file last changed in git (the `last_updated` setting).
    pub last_updated: bool,
    /// The GitHub repository from the settings file, for "Edit on GitHub".
    pub github_repo: Option<String>,
    /// The footer's details, for a file in git.
    pub page_meta: Option<crate::pagemeta::PageMeta>,
}

impl PageOptions {
    /// With the footer details for `file`, if they're wanted and it's in git.
    pub fn with_meta_for(mut self, file: &std::path::Path, cached: bool) -> Self {
        if self.last_updated && file.is_file() {
            let repo = self.github_repo.as_deref();
            self.page_meta = if cached {
                crate::pagemeta::cached(file, repo)
            } else {
                crate::pagemeta::for_file(file, repo)
            };
        }
        self
    }
}

