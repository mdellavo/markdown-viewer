/// Turns ```mermaid fences into `<pre class="mermaid">` blocks for
/// mermaid.js to draw in the browser (as GitHub does).
struct MermaidAdapter {
    sourcepos: bool,
}

impl CodefenceRendererAdapter for MermaidAdapter {
    fn write(
        &self,
        output: &mut dyn std::fmt::Write,
        fence: &CodefenceMeta<'_>,
    ) -> std::fmt::Result {
        let pos = match (self.sourcepos, fence.sourcepos) {
            (true, Some(sp)) => format!(" data-sourcepos=\"{sp}\""),
            _ => String::new(),
        };
        writeln!(
            output,
            "<pre class=\"mermaid\"{pos}>{}</pre>",
            escape_text(fence.code)
        )
    }
}

/// Results kept between renders, by content: a page is re-rendered on every
/// save, and most of its code blocks and drawings haven't changed. Cleared
/// when it grows past `RENDER_CACHE_BYTES`.
struct RenderCache {
    /// (kind, text) → HTML, and the total size.
    entries: std::sync::Mutex<(CacheMap, usize)>,
}

type CacheMap = std::collections::HashMap<(String, String), String>;

const RENDER_CACHE_BYTES: usize = 32 * 1024 * 1024;

impl RenderCache {
    fn new() -> Self {
        Self {
            entries: std::sync::Mutex::new((std::collections::HashMap::new(), 0)),
        }
    }

    fn get_or(&self, kind: &str, code: &str, make: impl FnOnce() -> String) -> String {
        let key = (kind.to_string(), code.to_string());
        if let Some(hit) = self.entries.lock().unwrap().0.get(&key) {
            return hit.clone();
        }
        let value = make();
        let mut entries = self.entries.lock().unwrap();
        let size = key.0.len() + key.1.len() + value.len();
        if entries.1 + size > RENDER_CACHE_BYTES {
            entries.0.clear();
            entries.1 = 0;
        }
        entries.1 += size;
        entries.0.insert(key, value.clone());
        value
    }
}

/// syntect, remembering highlighted blocks (the slow part of rendering).
struct CachedHighlighter {
    inner: SyntectAdapter,
    cache: RenderCache,
}

impl SyntaxHighlighterAdapter for CachedHighlighter {
    fn write_highlighted(
        &self,
        output: &mut dyn std::fmt::Write,
        highlight: &SyntaxHighlightMeta<'_>,
    ) -> std::fmt::Result {
        let html = self.cache.get_or(highlight.lang, highlight.code, || {
            let mut s = String::new();
            let _ = self.inner.write_highlighted(&mut s, highlight);
            s
        });
        output.write_str(&html)
    }

    fn write_pre_tag(
        &self,
        output: &mut dyn std::fmt::Write,
        highlight: &SyntaxHighlightMeta<'_>,
        attributes: std::collections::BTreeMap<&str, std::borrow::Cow<'_, str>>,
    ) -> std::fmt::Result {
        self.inner.write_pre_tag(output, highlight, attributes)
    }

    fn write_code_tag(
        &self,
        output: &mut dyn std::fmt::Write,
        highlight: &SyntaxHighlightMeta<'_>,
        attributes: std::collections::BTreeMap<&str, std::borrow::Cow<'_, str>>,
    ) -> std::fmt::Result {
        self.inner.write_code_tag(output, highlight, attributes)
    }
}

/// Stands in for a drawing's `data-sourcepos` in the cache.
const POS_MARK: &str = "\u{1}pos\u{1}";

/// Turns fences such as ```geojson, ```stl and ```pikchr into drawings
/// (maps, 3D models, diagrams), made here as SVG (`DRAWINGS`).
struct DrawingAdapter {
    sourcepos: bool,
    lang: &'static str,
    draw: Draw,
    /// Drawings by text, with `POS_MARK` where the source position goes.
    cache: std::sync::Arc<RenderCache>,
}

impl CodefenceRendererAdapter for DrawingAdapter {
    fn write(
        &self,
        output: &mut dyn std::fmt::Write,
        fence: &CodefenceMeta<'_>,
    ) -> std::fmt::Result {
        let pos = match (self.sourcepos, fence.sourcepos) {
            (true, Some(sp)) => format!(" data-sourcepos=\"{sp}\""),
            _ => String::new(),
        };
        let html = self
            .cache
            .get_or(self.lang, fence.code, || (self.draw)(fence.code, POS_MARK));
        output.write_str(&html.replacen(POS_MARK, &pos, 1))
    }
}

/// Turns fences drawn by a library in the page (```vega-lite, ```abc,
/// ```smiles) into `<pre class="mdv-lib-…">` blocks with the source, for
/// libraries-init.js; like Mermaid's.
struct LibraryAdapter {
    sourcepos: bool,
    class: &'static str,
}

impl CodefenceRendererAdapter for LibraryAdapter {
    fn write(
        &self,
        output: &mut dyn std::fmt::Write,
        fence: &CodefenceMeta<'_>,
    ) -> std::fmt::Result {
        let pos = match (self.sourcepos, fence.sourcepos) {
            (true, Some(sp)) => format!(" data-sourcepos=\"{sp}\""),
            _ => String::new(),
        };
        writeln!(
            output,
            "<pre class=\"mdv-lib {}\"{pos}>{}</pre>",
            self.class,
            escape_text(fence.code)
        )
    }
}

