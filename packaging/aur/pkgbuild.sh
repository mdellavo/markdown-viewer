#!/usr/bin/env bash
# Write the AUR package markdown-viewer-bin (PKGBUILD and .SRCINFO) for a
# release, using its prebuilt Linux archives.
# Usage: pkgbuild.sh <version> <dir containing markdown-viewer-<target>.tar.gz.sha256 files> <output dir>
# Set AUR_MAINTAINER (e.g. "Name <email>") to add a Maintainer line.
#
# .SRCINFO is normally made by `makepkg --printsrcinfo`, which needs Arch;
# this writes the same thing so releases can run anywhere. CI checks the two
# agree (the aur job in ci.yml).
set -euo pipefail

version=$1
dist=$2
out=$3
repo="https://github.com/mdellavo/markdown-viewer"
desc="Render a Markdown file with GitHub styling and live-reload it in your browser"

sha() { cut -d' ' -f1 "$dist/markdown-viewer-$1-unknown-linux-gnu.tar.gz.sha256"; }
# The archive names don't include the version, so give each download a
# versioned local name (makepkg caches sources by file name).
src() { echo "markdown-viewer-$version-$1.tar.gz::$repo/releases/download/v$version/markdown-viewer-$1-unknown-linux-gnu.tar.gz"; }

optdepends=(
  "chromium: --pdf, and app windows (or Chrome, Edge, Brave, Vivaldi)"
  "curl: --check-links --online"
  "git: showing changes since the last commit"
  "xdg-utils: opening the default browser"
  "wl-clipboard: --clipboard on Wayland"
  "xclip: --clipboard on X11"
)

mkdir -p "$out"
{
  if [ -n "${AUR_MAINTAINER:-}" ]; then echo "# Maintainer: $AUR_MAINTAINER"; fi
  echo "# Generated by packaging/aur/pkgbuild.sh in $repo"
  echo "pkgname=markdown-viewer-bin"
  echo "pkgver=$version"
  echo "pkgrel=1"
  echo "pkgdesc=\"$desc\""
  echo "arch=('x86_64' 'aarch64')"
  echo "url=\"$repo\""
  echo "license=('MIT')"
  echo "depends=('gcc-libs' 'glibc')"
  echo "optdepends=("
  for o in "${optdepends[@]}"; do echo "  '$o'"; done
  echo ")"
  echo "provides=('markdown-viewer')"
  echo "conflicts=('markdown-viewer')"
  # A prebuilt binary: no debug package.
  echo "options=('!debug')"
  echo "source_x86_64=(\"$(src x86_64)\")"
  echo "source_aarch64=(\"$(src aarch64)\")"
  echo "sha256sums_x86_64=('$(sha x86_64)')"
  echo "sha256sums_aarch64=('$(sha aarch64)')"
  cat <<'PKG'

package() {
  cd "markdown-viewer-$CARCH-unknown-linux-gnu"
  install -Dm755 markdown-viewer "$pkgdir/usr/bin/markdown-viewer"
  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
  install -Dm644 README.md CHANGELOG.md -t "$pkgdir/usr/share/doc/$pkgname/"
  install -Dm644 man/markdown-viewer.1 "$pkgdir/usr/share/man/man1/markdown-viewer.1"
  install -Dm644 completions/markdown-viewer.bash "$pkgdir/usr/share/bash-completion/completions/markdown-viewer"
  install -Dm644 completions/_markdown-viewer "$pkgdir/usr/share/zsh/site-functions/_markdown-viewer"
  install -Dm644 completions/markdown-viewer.fish "$pkgdir/usr/share/fish/vendor_completions.d/markdown-viewer.fish"
}
PKG
} > "$out/PKGBUILD"

{
  echo "pkgbase = markdown-viewer-bin"
  printf '\tpkgdesc = %s\n' "$desc"
  printf '\tpkgver = %s\n' "$version"
  printf '\tpkgrel = 1\n'
  printf '\turl = %s\n' "$repo"
  printf '\tarch = x86_64\n\tarch = aarch64\n'
  printf '\tlicense = MIT\n'
  printf '\tdepends = gcc-libs\n\tdepends = glibc\n'
  for o in "${optdepends[@]}"; do printf '\toptdepends = %s\n' "$o"; done
  printf '\tprovides = markdown-viewer\n'
  printf '\tconflicts = markdown-viewer\n'
  printf '\toptions = !debug\n'
  printf '\tsource_x86_64 = %s\n' "$(src x86_64)"
  printf '\tsha256sums_x86_64 = %s\n' "$(sha x86_64)"
  printf '\tsource_aarch64 = %s\n' "$(src aarch64)"
  printf '\tsha256sums_aarch64 = %s\n' "$(sha aarch64)"
  echo
  echo "pkgname = markdown-viewer-bin"
} > "$out/.SRCINFO"
